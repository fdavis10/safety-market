class CategoryListView(APIView):
    def get(self, request):
        return Response(
            [
                {
                    "id": value,
                    "label": label,
                    "count": Service.objects.filter(is_active=True, category=value).count(),
                }
                for value, label in Service.Category.choices
            ]
        )


class ServiceListView(APIView):
    def get(self, request):
        qs = Service.objects.filter(is_active=True)
        category = request.query_params.get("category")
        if category:
            qs = qs.filter(category=category)
        return Response(ServiceSerializer(qs, many=True).data)


class ServiceDetailView(APIView):
    def get(self, request, pk):
        service = Service.objects.filter(is_active=True, pk=pk).first()
        if not service:
            return Response({"detail": "Услуга не найдена."}, status=404)
        return Response(ServiceSerializer(service).data)


class PackageListView(APIView):
    def get(self, request):
        qs = Package.objects.prefetch_related("services")
        return Response(PackageSerializer(qs, many=True).data)
